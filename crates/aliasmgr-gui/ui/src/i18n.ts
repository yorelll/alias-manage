const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { en, zh };

/**
 * Keys whose Chinese and English copy is intentionally identical (brand names,
 * shell/product names, and literal example placeholders).
 */
export const IDENTICAL_TRANSLATION_KEYS: ReadonlySet<TranslationKey> = new Set<TranslationKey>([
  "app.title",
  "detail.id",
  "generated.shell",
  "override.false",
  "override.shell",
  "override.true",
  "settings.languageEn",
  "settings.languageZh",
  "shell.bash",
  "shell.fish",
  "shell.posixSh",
  "shell.powershell5",
  "shell.powershell7",
  "shell.zsh",
  "status.shell",
  "target.cmdlet",
  "target.javaJar",
  "wizard.cwdPlaceholder",
  "wizard.namePlaceholder",
  "wizard.shellFallback",
  "wizard.targetPlaceholder",
]);

export function isLanguage(value: unknown): value is Language {
  return value === "zh" || value === "en";
}

export function normalizeLanguage(value: unknown): Language {
  return isLanguage(value) ? value : DEFAULT_LANGUAGE;
}

export function hasTranslation(key: string): key is TranslationKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  ));
}

/** Translate `key` into `language`, interpolating `{name}` placeholders. */
export function t(language: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const dictionary = DICTIONARIES[normalizeLanguage(language)];
  return interpolate(dictionary[key] ?? en[key] ?? key, params);
}

/** `zh-CN` / `en` value for the document root's `lang` attribute. */
export function htmlLang(language: Language): string {
  return language === "zh" ? "zh-CN" : "en";
}

/** Keys missing or empty in either dictionary; empty means every key is complete. */
export function translationIssues(): string[] {
  const issues: string[] = [];
  for (const key of translationKeys()) {
    for (const language of ["en", "zh"] as const) {
      const value = DICTIONARIES[language][key];
      if (typeof value !== "string" || value.trim().length === 0) {
        issues.push(`${language}:${key}`);
      }
    }
  }
  for (const key of Object.keys(zh)) {
    if (!Object.prototype.hasOwnProperty.call(en, key)) issues.push(`zh-only:${key}`);
  }
  return issues;
}

/** Keys whose Chinese copy is identical to English without being allowlisted. */
export function untranslatedKeys(): TranslationKey[] {
  return translationKeys().filter((key) => (
    en[key] === zh[key] && !IDENTICAL_TRANSLATION_KEYS.has(key)
  ));
}

/** All dictionary keys, for completeness tests. */
export function translationKeys(): TranslationKey[] {
  return Object.keys(en) as TranslationKey[];
}
